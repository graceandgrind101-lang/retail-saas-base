import { sql } from "drizzle-orm";
import { getTableConfig, index, text } from "drizzle-orm/pg-core";
import { generateDrizzleJson, generateMigration } from "drizzle-kit/api";
import { afterAll, describe, expect, it } from "vitest";
import { checkDatabaseSecurity } from "../src/ci/security-check";
import { appSchema, platformSchema, tenantTable, tenants } from "../src/schema";
import { industry, tenantStatus } from "../src/schema/platform";
import { adminSql, newId } from "./helpers";
import { leakSuite } from "./leak-suite";
import { dropTables } from "./probe-tables";

const widget = tenantTable("zz_widget", { name: text("name").notNull() }, (t) => [
  index("zz_widget_tenant_name_idx").on(t.tenantId, t.name),
]);

describe("tenantTable() definition", () => {
  const config = getTableConfig(widget);

  it("lives in the app schema", () => {
    expect(config.schema).toBe("app");
    expect(config.name).toBe("zz_widget");
  });

  it("has the standard columns plus the table's own", () => {
    expect(config.columns.map((c) => c.name)).toEqual(["id", "tenant_id", "created_at", "updated_at", "created_by", "name"]);
  });

  it("id is the primary key with no database default (ids are made by the application)", () => {
    const id = config.columns.find((c) => c.name === "id");
    expect(id?.primary).toBe(true);
    expect(id?.hasDefault).toBe(false);
  });

  it("tenant_id is required", () => {
    expect(config.columns.find((c) => c.name === "tenant_id")?.notNull).toBe(true);
  });

  it("has unique (tenant_id, id), so composite foreign keys can target it", () => {
    const unique = config.uniqueConstraints.find((u) => u.name === "zz_widget_tenant_id_id_unique");
    expect(unique?.columns.map((c) => c.name)).toEqual(["tenant_id", "id"]);
  });

  it("references platform.tenants", () => {
    expect(config.foreignKeys).toHaveLength(1);
    const reference = config.foreignKeys[0]?.reference();
    expect(getTableConfig(reference?.foreignTable as typeof tenants).name).toBe("tenants");
    expect(reference?.columns.map((c) => c.name)).toEqual(["tenant_id"]);
  });

  it("keeps the table's own extra config (indexes)", () => {
    expect(config.indexes.map((i) => i.config.name)).toContain("zz_widget_tenant_name_idx");
  });
});

// Round trip: DDL generated by drizzle-kit from the helper's own output, applied to a real
// database, secured with the production function, then put through the same checks as every
// real table. This ties the TypeScript helper to the SQL it must work with.
const admin = adminSql();
const base = { platformSchema, appSchema, tenants, industry, tenantStatus };
const statements = await generateMigration(
  await generateDrizzleJson(base),
  await generateDrizzleJson({ ...base, widget }),
);
await dropTables(admin, "zz_widget");
for (const statement of statements) await admin.unsafe(statement);
await admin.unsafe("select private.secure_tenant_table('app.zz_widget')");

describe("tenantTable() against a real database", () => {
  it("generated SQL that creates exactly the one table", () => {
    expect(statements.join("\n")).toContain('CREATE TABLE "app"."zz_widget"');
    expect(statements.join("\n")).not.toContain('CREATE TABLE "platform"');
  });

  it("produces a table that passes the database security check", async () => {
    const violations = (await checkDatabaseSecurity(admin)).filter((v) => v.scope === "app.zz_widget");
    expect(violations).toEqual([]);
  });
});

leakSuite("zz_widget", (tenantId) => sql`insert into app.zz_widget (id, tenant_id, name) values (${newId()}, ${tenantId}, 'w')`);

afterAll(async () => {
  await dropTables(admin, "zz_widget");
  await admin.end();
});
